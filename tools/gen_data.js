// Generates plugins/Harder/Data.hpp from the web app's sound library and groove library.
const fs = require('fs'), path = require('path');
const W = require('./webcore.js'), C = W.C;
const q = s => JSON.stringify(s);
const mid = m => C.MACHINE_IDS.indexOf(m);
let o = '// GENERATED by tools/gen_data.js from the web build (presets.baked.js, grooves.js). Do not edit.\n#pragma once\n#include <cstdint>\nnamespace hd {\n';
o += `static const char* const MATS[] = { ${W.MATS.map(q).join(', ')} };\nconstexpr int NMATS = ${W.MATS.length};\n`;
o += `static const char* const MAT_DESC[] = { ${W.MATS.map(m => q(W.MAT_DESC[m])).join(', ')} };\n`;
o += `static const char* const FUNCS[] = { ${W.FUNCS.map(q).join(', ')} };\nconstexpr int NFUNCS = ${W.FUNCS.length};\n`;
o += `static const char* const ROLES[] = { ${W.ROLES.map(q).join(', ')} };\nconstexpr int NROLES = ${W.ROLES.length};\n`;
o += `static const char* const ROLE_NAMES[] = { ${W.ROLES.map(r => q(W.ROLE_NAMES[r])).join(', ')} };\n`;
o += 'struct KV { int8_t i; double v; };\n';
o += 'struct PresetDef { const char* n; int8_t f; int8_t m; int8_t mat; double s[8]; int8_t no; KV o[24]; };\n';
o += `static const PresetDef PRESETS[] = {\n`;
for (const p of W.PRESETS) {
  const ov = Object.entries(p.o || {}).map(([k, v]) => `{${k}, ${v}}`);
  if (ov.length > 24) throw new Error('too many overrides ' + p.n);
  o += `  { ${q(p.n)}, ${W.FUNCS.indexOf(p.f)}, ${mid(p.m)}, ${W.MATS.indexOf(W.MATERIAL(p))}, { ${p.s.map(v => String(v)).join(', ')} }, ${ov.length}, { ${ov.join(', ')} } },\n`;
  if (W.FUNCS.indexOf(p.f) < 0 || mid(p.m) < 0) throw new Error('bad preset ' + p.n);
}
o += `};\nconstexpr int NPRESETS = ${W.PRESETS.length};\n`;
o += 'struct KitTrack { int16_t preset; int8_t no; KV o[8]; };\nstruct KitDef { const char* name; const char* desc; int8_t nm; KV master[16]; KitTrack t[8]; };\n';
o += 'static const KitDef KITS[] = {\n';
for (const k of W.KITS) {
  const mv = Object.entries(k.master).map(([i, v]) => `{${i}, ${v}}`);
  const tr = k.t.map(([n, ov]) => { const pi = W.PRESETS.findIndex(p => p.n === n); if (pi < 0) throw new Error('kit preset ' + n); const e = Object.entries(ov).map(([i, v]) => `{${i}, ${v}}`); return `{ ${pi}, ${e.length}, { ${e.join(', ')} } }`; });
  o += `  { ${q(k.name)}, ${q(k.desc)}, ${mv.length}, { ${mv.join(', ')} }, { ${tr.join(', ')} } },\n`;
}
o += `};\nconstexpr int NKITS = ${W.KITS.length};\n`;
// grooves
const G = W.GROOVES, styles = Object.keys(G.styles);
const LET = 'KSCHOPTX';
o += 'struct SeedDef { const char* line[8]; };   // K S C H O P T X, bars separated by |\n';
o += 'struct StyleDef { const char* name; double bpm, swing; double micro[8]; int8_t scl[8]; int8_t nseeds; SeedDef seeds[4]; };\n';
o += 'static const StyleDef STYLES[] = {\n';
for (const n of styles) {
  const s = G.styles[n]; if (s.seeds.length > 4) throw new Error('seeds');
  const micro = [...LET].map(L => (s.micro && s.micro[L]) || 0), scl = [...LET].map(L => (s.scl && s.scl[L]) || 0);
  const seeds = s.seeds.map(sd => `{ { ${[...LET].map(L => q(sd[L] || '')).join(', ')} } }`);
  o += `  { ${q(n)}, ${s.bpm}, ${s.swing}, { ${micro.join(', ')} }, { ${scl.join(', ')} }, ${s.seeds.length}, { ${seeds.join(', ')} } },\n`;
}
o += `};\nconstexpr int NSTYLES = ${styles.length};\n`;
o += 'struct FamilyDef { const char* name; const char* desc; int8_t n; int8_t styles[8]; };\nstatic const FamilyDef FAMILIES[] = {\n';
for (const [f, names, desc] of G.families) o += `  { ${q(f)}, ${q(desc)}, ${names.length}, { ${names.map(x => { const i = styles.indexOf(x); if (i < 0) throw new Error(x); return i; }).join(', ')} } },\n`;
o += `};\nconstexpr int NFAMILIES = ${G.families.length};\n`;
o += '} // namespace hd\n';
fs.writeFileSync(path.join(__dirname, '../plugins/Harder/Data.hpp'), o);
console.log('Data.hpp', o.length, 'bytes', W.PRESETS.length, 'presets', W.KITS.length, 'kits', styles.length, 'styles');
